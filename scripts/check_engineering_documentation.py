"""Check all documented AI-engineering definitions and optionally rebuild their index.

Run from the repository root with the base Python interpreter. This command uses
only the standard library: no model, database, HTTP request or package install is
performed. The scope is declared in docs/engineering/documentation-scope.json.
Default operation is read-only. --write-index replaces the generated function
index, and --json-out writes a machine-readable report at the selected path.
Exit status 0 means documentation coverage passes; 1 means missing documentation;
2 is argparse's usage-error status. Coverage does not prove prose accuracy or
model/service acceptance. See docs/engineering/RUNBOOK.md for the review procedure.
"""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import re


def definitions(node, prefix=""):
    """Yield qualified class/function definitions, including those in control flow.

    Args:
        node: Parsed Python AST node to traverse; never evaluated.
        prefix: Enclosing dotted class/function name, including its final dot.

    Yields:
        (qualified_name, node) tuples in source traversal order. Lambdas have no
        Python docstring slot and are counted separately at their call sites.
    """
    for child in ast.iter_child_nodes(node):
        if isinstance(child, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            name = prefix + child.name
            yield name, child
            yield from definitions(child, name + ".")
        else:
            yield from definitions(child, prefix)


def check_python(path, relative):
    """Inspect one module for documented definitions and parameter names.

    Args:
        path: Path of the UTF-8 Python source file to read.
        relative: Repository-relative name used in diagnostics and source links.

    Returns:
        Dictionary with function/class counts, definition records, anonymous
        callback lines and missing-doc/parameter errors. self and cls do not
        need separate parameter entries. A parameter mention is a coverage
        check only: a human must verify the contract's meaning.

    Raises:
        OSError: Source cannot be read.
        SyntaxError: Source is not valid Python.
    """
    source = path.read_text(encoding="utf-8-sig")
    tree = ast.parse(source, filename=relative)
    result = {"file": relative, "functions": 0, "classes": 0, "definitions": [], "errors": []}
    if not ast.get_docstring(tree):
        result["errors"].append({"name": "<module>", "problem": "missing module docstring"})
    for name, node in definitions(tree):
        kind = "class" if isinstance(node, ast.ClassDef) else "function"
        result["classes" if kind == "class" else "functions"] += 1
        doc = ast.get_docstring(node) or ""
        signature = ""
        if kind == "function":
            signature = "(" + ast.unparse(node.args) + ")"
        result["definitions"].append({"name": name, "kind": kind, "line": node.lineno,
                                      "signature": signature, "summary": doc.splitlines()[0] if doc else ""})
        if not doc.strip():
            result["errors"].append({"name": name, "line": node.lineno, "problem": "missing docstring"})
            continue
        if kind == "function":
            arguments = node.args.posonlyargs + node.args.args + node.args.kwonlyargs
            arguments += [x for x in (node.args.vararg, node.args.kwarg) if x is not None]
            missing = [a.arg for a in arguments if a.arg not in ("self", "cls")
                       and not re.search(r"\b" + re.escape(a.arg) + r"\b", doc)]
            if missing:
                result["errors"].append({"name": name, "line": node.lineno,
                                          "problem": "parameters not named in contract", "parameters": missing})
    result["anonymous_callback_lines"] = [n.lineno for n in ast.walk(tree) if isinstance(n, ast.Lambda)]
    return result


def write_index(root, reports, javascript):
    """Replace the generated source-linked index after successful coverage checks.

    Args:
        root: Repository root Path containing the documented source tree.
        reports: Successful check_python result dictionaries in scope order.
        javascript: Relative JavaScript filename documented in the portal guide.

    Returns:
        Path of docs/engineering/FUNCTION_INDEX.md, overwritten in UTF-8.

    Raises:
        OSError: The generated documentation cannot be written.

    Notes:
        Links use current source line numbers. Rebuild after edits move definitions.
        Parameter names, summaries and qualified nested names come from the AST;
        this command does not invent or execute any function contract.
    """
    lines = ["# AI engineering function index", "", "Generated by `python scripts/check_engineering_documentation.py --write-index`.",
             "", "Start with the [runbook](RUNBOOK.md), then use this complete source index for individual contracts.", ""]
    for report in reports:
        lines.extend(["## " + report["file"], "", "| Definition | Contract |", "| --- | --- |"])
        for item in report["definitions"]:
            label = (item["name"] + item["signature"]).replace("|", "\\|")
            summary = item["summary"].replace("|", "\\|")
            lines.append(f"| [`{label}`](../../{report['file']}#L{item['line']}) | {summary} |")
        lines.extend(["", "Anonymous call-site callbacks: " + str(len(report["anonymous_callback_lines"])) + ". Their purpose is documented next to the lambda.", ""])
    lines.extend(["## Browser procedures and callbacks", "", f"[{javascript}](../../{javascript}) uses JSDoc for named procedures and handlers, plus call-site comments for callbacks.",
                  "See the [portal reference](portal-reference.md) for each route, handler, input, output and failure path.", ""])
    path = root / "docs/engineering/FUNCTION_INDEX.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main(argv=None):
    """Run documentation checks and the explicitly requested report/index writes.

    Args:
        argv: Optional sequence of CLI arguments; None reads sys.argv. Options
            are --root, --json-out and --write-index. Defaults to this checkout.

    Returns:
        0 for complete named-definition/parameter coverage; 1 for coverage errors.

    Raises:
        SystemExit: argparse reports an invalid command line (normally status 2).
        OSError: A source, scope manifest or requested output cannot be accessed.
        ValueError: Scope JSON is malformed or source paths escape the checkout.
        SyntaxError: A scoped module is invalid Python.

    Notes:
        No source code is imported. The normal check is read-only; --write-index
        writes only after coverage succeeds. --json-out preserves the detailed
        diagnostics even for a failing check. Existing report paths are replaced.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--json-out", type=Path)
    parser.add_argument("--write-index", action="store_true")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    scope = json.loads((root / "docs/engineering/documentation-scope.json").read_text(encoding="utf-8"))
    reports = []
    for relative in scope["python"]:
        path = (root / relative).resolve()
        if not path.is_relative_to(root):
            raise ValueError("Documentation source path escapes the repository")
        reports.append(check_python(path, relative))
    errors = [dict(file=r["file"], **e) for r in reports for e in r["errors"]]
    report = {"scope": "AI engineering extension and adjacent local RAG contracts",
              "functions": sum(r["functions"] for r in reports),
              "classes": sum(r["classes"] for r in reports),
              "anonymous_python_callbacks": sum(len(r["anonymous_callback_lines"]) for r in reports),
              "errors": errors, "passed": not errors, "files": reports,
              "javascript": {"file": scope["javascript"], "review": "JSDoc and callback comments require prose/token review"}}
    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    if not errors and args.write_index:
        write_index(root, reports, scope["javascript"])
    print(json.dumps({k: report[k] for k in ("functions", "classes", "anonymous_python_callbacks", "passed", "errors")}))
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
